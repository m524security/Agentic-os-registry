#!/usr/bin/env python3
"""Derive the registry indexes and the human-readable catalog from the agent manifests (the source of truth).

Writes registry/agents.json, agents.csv, prompt-index.json, role-contracts.txt, agents/<category>/README.md, docs/AGENTS.md and the
generated blocks of README.md (between <!-- NAME:START --> and <!-- NAME:END --> markers). `--check` reports drift without writing."""
import argparse, csv, hashlib, io, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'brain'))
import runtime  # noqa: E402  (route_weights builds the precomputed routing index)

def manifests():
    out = []
    for f in (ROOT / 'agents').glob('*/AGENT-*/manifest.json'):
        out.append((f, json.loads(f.read_text(encoding='utf-8'))))
    return sorted(out, key=lambda x: int(x[1]['id'][6:]))

def dump(value): return json.dumps(value, indent=2, ensure_ascii=False) + '\n'
def sentence(text): return text if text.endswith('.') else text + '.'
def skills():
    rows = []
    for p in sorted((ROOT / 'skills').glob('*/SKILL.md')):
        desc = re.search(r'^description: "(.*)"$', p.read_text(encoding='utf-8'), re.M)
        rows.append((p.parent.name, desc.group(1) if desc else ''))
    return rows

def groups(ms):
    """Ordered {category: {group: [manifests]}} with categories and groups ordered by their lowest agent number."""
    cats = {}
    for _, m in ms: cats.setdefault(m['category'], {}).setdefault(m['group'], []).append(m)
    ordered = sorted(cats.items(), key=lambda kv: min(int(x['id'][6:]) for g in kv[1].values() for x in g))
    return [(c, sorted(g.items(), key=lambda kv: min(int(x['id'][6:]) for x in kv[1]))) for c, g in ordered]

def registry_files(ms):
    agents = [{'id': m['id'], 'name': m['name'], 'category': m['category'], 'group': m['group'], 'kind': 'agent-capability', 'deploy': 'dynamic',
               'status': m['status'], 'purpose': m['mission'], 'verification': m['verification'][0]} for _, m in ms]
    index = [{'id': m['id'], 'name': m['name'], 'category': m['category'], 'mission': m['mission'], 'manifest_path': f.relative_to(ROOT).as_posix(),
              'system_prompt_path': (f.parent / m['system_prompt_path']).resolve().relative_to(ROOT).as_posix(), 'system_prompt_sha256': m['system_prompt_sha256']} for f, m in ms]
    buf = io.StringIO(); w = csv.writer(buf, lineterminator='\n'); w.writerow(list(agents[0]))
    for a in agents: w.writerow(list(a.values()))
    contracts = ''.join('%s|%s|%s|%s\n' % (m['id'][6:], m['mission'], m['specialist_method'], m['verification'][0]) for _, m in ms)
    index_text = dump(index)
    rows = {r['id']: r for r in index}
    route = {'_note': 'Generated by scripts/build_catalog.py; speeds up routing. Ignored automatically when prompt-index.json changes.',
             'source_sha256': hashlib.sha256(index_text.encode('utf-8')).hexdigest(), 'weights': runtime.route_weights(rows, ROOT)}
    return {'registry/agents.json': dump(agents), 'registry/agents.csv': buf.getvalue(), 'registry/prompt-index.json': index_text,
            'registry/role-contracts.txt': contracts, 'registry/route-index.json': json.dumps(route, separators=(',', ':'), sort_keys=True) + '\n'}

def category_readmes(ms):
    out = {}
    for cat, grps in groups(ms):
        lines = ['# ' + cat, '', '%d definitions in %d groups. Each entry links to the exact system prompt.' % (sum(len(v) for _, v in grps), len(grps)), '']
        for name, items in grps:
            lines += ['## ' + name, ''] + ['- [%s — %s](%s/system-prompt.md) — %s' % (m['id'], m['name'], m['id'], sentence(m['mission'])) for m in items] + ['']
        out['agents/%s/README.md' % cat] = '\n'.join(lines).rstrip() + '\n'
    return out

def agents_doc(ms):
    lines = ['# Agent directory', '', 'Every agent, what it does and what makes its approach specific. The text under "Specialization" is compiled into the agent\'s prompt',
             'from `registry/expertise.json`. Regenerate this file with `python scripts/build_all.py`.', '']
    for cat, grps in groups(ms):
        lines += ['## ' + cat, '']
        for name, items in grps:
            lines += ['### ' + name, '', '| ID | Agent | What it does | Specialization |', '| --- | --- | --- | --- |']
            lines += ['| [%s](../%s) | %s | %s | %s |' % (m['id'], (f.parent / 'system-prompt.md').relative_to(ROOT).as_posix(), m['name'], sentence(m['mission']),
                      m['specialist_focus'].replace('|', '/')) for f, m in [x for x in ms if x[1] in items]]
            lines.append('')
    return {'docs/AGENTS.md': '\n'.join(lines).rstrip() + '\n'}

def blocks(ms):
    cats = groups(ms); sk = skills()
    stats = ('%d agents (the executive brain AGENT-000 and %d specialists and advisers) in %d groups across %d categories, %d skills, %d generated Claude Code subagents.'
             % (len(ms), len(ms) - 1, sum(len(g) for _, g in cats), len(cats), len(sk), len(ms)))
    summary = ['| Category | Groups | Agents |', '| --- | --- | ---: |'] + ['| %s | %s | %d |' % (c, ', '.join(n for n, _ in g), sum(len(v) for _, v in g)) for c, g in cats]
    listing = []
    for cat, grps in cats:
        listing += ['### ' + cat, '']
        for name, items in grps:
            listing += ['**%s** (%d)' % (name, len(items)), '', '| ID | Agent | What it does |', '| --- | --- | --- |']
            listing += ['| %s | %s | %s |' % (m['id'], m['name'], sentence(m['mission'])) for m in items] + ['']
    skill_rows = ['| Skill | What it gives an agent |', '| --- | --- |'] + ['| `%s` | %s |' % (n, d) for n, d in sk]
    return {'STATS': stats, 'AGENT_SUMMARY': '\n'.join(summary), 'AGENTS': '\n'.join(listing).rstrip(), 'SKILLS': '\n'.join(skill_rows)}

def coverage_docs(ms):
    cats = groups(ms); sk = skills()
    rows = []
    for cat, grps in cats:
        for name, items in grps:
            ids = [int(m['id'][6:]) for m in items]
            rows.append('| %s | %s | %d | %03d–%03d |' % (cat, name, len(items), min(ids), max(ids)))
    coverage = ('# Coverage\n\n%d definitions in %d groups across %d categories. Every group has a field-expertise pack and every agent has its own specialization focus, '
                'both compiled into its prompt from `registry/expertise.json` by `scripts/build_prompts.py`.\n\n| Category | Group | Agents | IDs |\n| --- | --- | ---: | --- |\n%s\n\n'
                'IDs within a group are not always contiguous. There is no objective universal count of necessary agents: roles are added when a task needs distinct expertise, '
                'a distinct authorization boundary or a distinct verification method, and merged or retired when they overlap. The executive brain (AGENT-000) schedules; '
                'AGENT-001 advises on strategy.\n') % (len(ms), sum(len(g) for _, g in cats), len(cats), '\n'.join(rows))
    counts = ('# Counts\n\n- %d definitions: the executive brain AGENT-000 and %d specialists and advisers.\n- %d groups, %d field-expertise packs, %d per-agent specialization focus lines (`registry/expertise.json`).\n'
              '- %d skills (`skills/<name>/SKILL.md`), each also generated as a Claude Code skill; %d generated Claude Code subagents.\n- Evaluation specifications: `evals/agent-cases.json`, not model-executed.\n'
              '- Automated tests: see `evals/BRAIN-TEST-RESULTS.json`.\n- 12 browser connection profiles and 10 MCP patterns; the browser agents attach a pinned Playwright MCP server in the Claude Code pack. Not live-tested here.\n') % (
              len(ms), len(ms) - 1, sum(len(g) for _, g in cats), sum(len(g) for _, g in cats), len(ms), len(sk), len(ms))
    return {'docs/COVERAGE.md': coverage, 'docs/COUNTS.md': counts}

def apply_blocks(text, values):
    for name, body in values.items():
        pattern = re.compile(r'(<!-- %s:START -->\n).*?(\n<!-- %s:END -->)' % (name, name), re.S)
        if not pattern.search(text): raise SystemExit('README.md is missing the %s block markers' % name)
        text = pattern.sub(lambda m: m.group(1) + body + m.group(2), text)
    return text

def run(write):
    ms = manifests(); files = {}
    files.update(registry_files(ms)); files.update(category_readmes(ms)); files.update(agents_doc(ms)); files.update(coverage_docs(ms))
    readme = (ROOT / 'README.md').read_text(encoding='utf-8'); files['README.md'] = apply_blocks(readme, blocks(ms))
    drift = []
    for rel, text in files.items():
        path = ROOT / rel
        if not path.exists() or path.read_bytes() != text.encode('utf-8'):
            drift.append(rel)
            if write: path.write_bytes(text.encode('utf-8'))
    return drift

def main():
    ap = argparse.ArgumentParser(description=__doc__); ap.add_argument('--check', action='store_true'); args = ap.parse_args()
    drift = run(write=not args.check)
    print(json.dumps({'status': 'passed' if not drift else ('failed' if args.check else 'rebuilt'), 'files': drift[:25], 'count': len(drift)}))
    sys.exit(2 if drift and args.check else 0)

if __name__ == '__main__':
    main()
